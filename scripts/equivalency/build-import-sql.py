"""Build the SQL that imports the scanned past papers as DRAFTS.

Input:  a directory of tesseract output, one sub-directory per scanned PDF
        (p-01.txt, p-02.txt, ...), plus the dir -> subject map below.
Output: SQL on stdout. Idempotent: each paper carries an import_key
        (<scan dir>:<first page>) and is skipped if that key already exists.

Paper boundaries are guessed from page headers («امتحان تنظيم مهنة القانون»,
«بسم الله», «السؤال الأول»). OCR garbles years, so exam_year is left empty;
the session month is kept only when the header names one. Every paper is
imported with status=draft and needs_review=true. Nothing becomes visible to
students until an editor checks it against the original and publishes it.

Usage: python3 -I build-import-sql.py OCR_DIR > out.sql
       python3 -I build-import-sql.py OCR_DIR --json > out.json
         (for the batch-import page /admin/equivalency/import)
"""
import json
import os, re, sys

SUBJECT_BY_DIR = {
    "1_20_29_PM": "criminal-procedure",
    "0ca5b5eb-1.21.21PM": "criminal-procedure",   # single page, Q6, photographed separately
    "2_26_37_PM": "criminal-law",
    "2_29_12_PM": "criminal-law",
    "3_24_34_PM": "personal-status",
    "3_27_14_PM": "personal-status",
    "3_38_52_PM": "evidence",
    "3_47_02_PM": "contracts",
    "caf6363e-3.48.08PM": "contracts",
    "3_53_53_PM": "civil-procedure",
    "37494da5-3.54.38PM": "civil-procedure",
}
MONTHS = [("فبر", "فبراير"), ("كبر", "فبراير"), ("قبرا", "فبراير"), ("اغس", "أغسطس"), ("أغس", "أغسطس"),
          ("يول", "يوليو"), ("يبول", "يوليو")]
START = re.compile(r"(امت?ه?د?حان|امنحان|امتدان).{0,8}تن?خ?ظ?ل?ب?م|تنظيم ?م?وهنة|تنظيم مهنة|ب?ص?سم ال?ل?ه? الرحمن")
FIRST_Q = re.compile(r"السؤال ال(أول|اول|أو)")

def read(p):
    return open(p, "rb").read().decode("utf-8", "ignore").replace("\x00", "")

def pages(d):
    fs = [f for f in os.listdir(d) if f.endswith(".txt")]
    return sorted(fs, key=lambda f: int(re.findall(r"\d+", f)[0]))

def segment(base):
    papers = []
    for d in sorted(os.listdir(base)):
        if d not in SUBJECT_BY_DIR:
            print(f"-- skipped unknown scan dir {d}", file=sys.stderr)
            continue
        cur = None
        for f in pages(os.path.join(base, d)):
            text = read(os.path.join(base, d, f))
            head = "\n".join(text.splitlines()[:9])
            new = bool(START.search(head)) or (bool(FIRST_Q.search(head)) and not (cur and FIRST_Q.search(cur["first"])))
            if new or cur is None:
                month = next((v for k, v in MONTHS if k in head), None)
                cur = {"dir": d, "subject": SUBJECT_BY_DIR[d], "pages": [], "texts": [], "month": month, "first": head}
                papers.append(cur)
            cur["pages"].append(f)
            cur["texts"].append(text.strip())
    return papers

def q(s):
    return "null" if s is None else "'" + s.replace("'", "''") + "'"

def records(papers):
    seq, out = {}, []
    for p in papers:
        seq[p["subject"]] = seq.get(p["subject"], 0) + 1
        n = seq[p["subject"]]
        pages_label = ", ".join(x.replace(".txt", "") for x in p["pages"])
        out.append({
            "import_key": f"scan:{p['dir']}:{p['pages'][0]}",
            "subject": p["subject"],
            "session_month": p["month"],
            "title_ar": f"مسودة مستوردة {n}" + (f" — دورة {p['month']}" if p["month"] else ""),
            "source_note": "نسخة مطبوعة من أرشيف صافي، مسحها ضوئياً",
            "review_note": (f"استيراد آلي من المسح {p['dir']} (الصفحات: {pages_label}). حدود الورقة والدورة مستنتجة آلياً"
                            " من رأس الصفحة، والسنة متروكة لأن القراءة الآلية تخطئ الأرقام. قابلها بالأصل: السنة، الدورة،"
                            " اكتمال الصفحات، وأرقام المواد."),
            "ocr_text": "\n\n— صفحة —\n\n".join(p["texts"]),
        })
    return out

def main():
    papers = segment(sys.argv[1])
    if "--json" in sys.argv:
        json.dump({"format": "makuria-eq-import/1", "papers": records(papers)}, sys.stdout, ensure_ascii=False)
        return
    seq = {}
    print("-- Generated by scripts/equivalency/build-import-sql.py — drafts only.")
    print(f"-- {len(papers)} papers.\n")
    for p in papers:
        seq[p["subject"]] = seq.get(p["subject"], 0) + 1
        n = seq[p["subject"]]
        key = f"scan:{p['dir']}:{p['pages'][0]}"
        pages_label = ", ".join(x.replace(".txt", "") for x in p["pages"])
        title = f"مسودة مستوردة {n}" + (f" — دورة {p['month']}" if p["month"] else "")
        note = (f"استيراد آلي من المسح {p['dir']} (الصفحات: {pages_label}). حدود الورقة والدورة مستنتجة آلياً"
                " من رأس الصفحة، والسنة متروكة لأن القراءة الآلية تخطئ الأرقام. قابلها بالأصل: السنة، الدورة،"
                " اكتمال الصفحات، وأرقام المواد.")
        ocr = "\n\n— صفحة —\n\n".join(p["texts"])
        print(f"""with s as (select id from public.eq_subjects where slug = {q(p['subject'])}),
ins as (
  insert into public.eq_papers (subject_id, session_month, title_ar, status, needs_review, source_note)
  select s.id, {q(p['month'])}, {q(title)}, 'draft', true, 'نسخة مطبوعة من أرشيف صافي، مسحها ضوئياً'
  from s
  where not exists (select 1 from public.eq_paper_internal where import_key = {q(key)})
  returning id
)
insert into public.eq_paper_internal (paper_id, ocr_text, review_note, import_key)
select id, {q(ocr)}, {q(note)}, {q(key)} from ins;
""")

if __name__ == "__main__":
    main()
